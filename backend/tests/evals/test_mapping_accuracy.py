"""
Mapping accuracy evaluation harness.

Marked `slow` and `evals` so it doesn't run by default in CI. To run:

    pytest backend/tests/evals/ -m evals --tb=short

This harness exercises the REAL OpenAI API against ground-truth fixtures
and reports per-template accuracy. It catches regressions when prompt
tweaks help one template but hurt another. Without it, "95% accuracy" is
a guess.

Ground truth source: the hand-crafted canonical mappings in
backend/mappings/*.json, generated by a human visually inspecting each
template. Those are the gold standard. Fixtures were extracted via
`scripts/build_eval_fixtures.py` (one-shot, re-runnable when templates
change).

Per-template targets (informational, not hard-fail by default):
  Lease Invoice:    >= 95% (small, well-labeled form)
  Lease Abstract:   >= 90%
  Multi-Board:      >= 80% (389 fields, hardest case)

The accuracy bar drops on Multi-Board because:
- 389 fields stress the AI's context window
- 22% of fields have no neighbor text (rely on visual crops)
- Numerical field names give no semantic signal
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from backend.pdf_render import collect_field_crops
from backend.templates import propose_mapping, validate_pdf

FIXTURES_DIR = Path(__file__).resolve().parent / "fixtures"


@pytest.mark.evals
@pytest.mark.parametrize("template_name,pdf_filename,target_accuracy", [
    (
        "lease_invoice",
        "2025 Compass Chicagoland Lease Invoice Landlords and Tenant Use copy.pdf",
        0.85,  # 6 expected paths out of 7 fields
    ),
    (
        "lease_abstract",
        "Lease Abstract Form.pdf",
        0.80,
    ),
    (
        "multiboard",
        "Multi-Board-8.0 (1).pdf",
        0.60,  # baseline target; goal is 80% but we accept 60% as "not regressed"
    ),
])
async def test_mapping_accuracy(template_name, pdf_filename, target_accuracy):
    """Run real AI mapping and compare to ground truth. Reports per-template
    accuracy. Fails if accuracy drops below `target_accuracy`."""
    fixtures_pdf = Path(__file__).resolve().parent.parent.parent.parent / "templates" / "pdf" / pdf_filename
    fields_fixture = FIXTURES_DIR / f"{template_name}_fields.json"
    expected_fixture = FIXTURES_DIR / f"{template_name}_expected.json"

    if not all(p.exists() for p in (fixtures_pdf, fields_fixture, expected_fixture)):
        pytest.skip(f"Missing fixtures for {template_name}")

    pdf_bytes = fixtures_pdf.read_bytes()
    reader = validate_pdf(pdf_bytes)
    field_descs = json.loads(fields_fixture.read_text())
    expected: dict[str, str | None] = json.loads(expected_fixture.read_text())

    # Render visual crops for empty-neighbor fields.
    crops = collect_field_crops(reader, field_descs)

    # Run the real AI mapping.
    proposal = await propose_mapping(field_descs, crops=crops)

    # Compare. We score:
    #   correct: canonical_path matches expected exactly
    #   wrong:   AI proposed a path but it doesn't match expected
    #   missing: expected has a path, AI proposed extra_field or nothing
    #   none-correct: expected has None (extra/unmapped) AND AI agrees
    correct = 0
    wrong = 0
    missing = 0
    by_field = {p.pdf_field: p for p in proposal.fields}

    for pdf_field, expected_path in expected.items():
        got = by_field.get(pdf_field)
        if got is None:
            if expected_path is None:
                correct += 1  # both agree it's not a canonical
            else:
                missing += 1
            continue
        got_path = got.canonical_path
        if expected_path == got_path:
            correct += 1
        elif expected_path is None:
            # Expected unmapped/extra; AI proposed canonical — count as wrong
            wrong += 1
        elif got_path is None:
            # Expected canonical; AI proposed extra/unmapped — count as missing
            missing += 1
        else:
            wrong += 1

    total = len(expected)
    accuracy = correct / total if total else 0.0

    print(f"\n{template_name}: {correct}/{total} = {accuracy:.0%} accuracy")
    print(f"  wrong:   {wrong}")
    print(f"  missing: {missing}")

    assert accuracy >= target_accuracy, (
        f"{template_name} accuracy {accuracy:.0%} below target {target_accuracy:.0%}"
    )
